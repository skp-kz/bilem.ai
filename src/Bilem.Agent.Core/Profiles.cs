    /// Правило MCP-слоя с первого дня: проводки по счетам оплаты труда (и расчётов с работниками, подотчётными,
    /// налогов и взносов с зарплаты) и проводки с физлицами в аналитике наружу не отдаются.
    /// В v0.1 инструментов с проводками нет (cash_balance отдаёт только агрегаты по счетам денег), правило — для следующих.
    /// </summary>
    public static class PostingPolicy
    {
        public static bool IsSensitiveAccount(ConfigProfile p, string accountCode) =>
            !string.IsNullOrEmpty(accountCode) && p.SensitiveAccountPrefixes.Any(x => accountCode.StartsWith(x, StringComparison.Ordinal));

        public static bool IsSensitiveExtDimension(ConfigProfile p, string extDimensionType) =>
            !string.IsNullOrEmpty(extDimensionType) && p.SensitiveExtDimensionTypes.Any(x => extDimensionType.IndexOf(x, StringComparison.Ordinal) >= 0);

        /// <summary>Можно ли отдать проводку наружу: ни один из её счетов не чувствительный и в аналитике нет физлиц.</summary>
        public static bool CanExpose(ConfigProfile p, IEnumerable<string> accountCodes, IEnumerable<string> extDimensionTypes) =>
            !(accountCodes ?? Enumerable.Empty<string>()).Any(c => IsSensitiveAccount(p, c))
            && !(extDimensionTypes ?? Enumerable.Empty<string>()).Any(t => IsSensitiveExtDimension(p, t));
    }
