    public enum CashClass { Cash, Bank, Other }

    /// <summary>
    /// Профиль конфигурации 1С: какие роли дать bilem, что включить в OData, какие счета — деньги,
    /// какие проводки наружу не отдаются. Проверено на «Бухгалтерии для Казахстана» 3.0 (спайк, заходы 2–4).
    /// </summary>
    public sealed class ConfigProfile
    {
        public string Configuration { get; set; }
        public string ChartOfAccounts { get; set; }
        public string AccountingRegister { get; set; }
        public string[] Roles { get; set; }
        public string[] ODataObjects { get; set; }
        /// <summary>Группа счетов денежных средств (код родителя) и префикс кодов счетов денег.</summary>
        public string MoneyGroupCode { get; set; }
        public Func<string, CashClass> ClassifyMoney { get; set; }
        /// <summary>Счета оплаты труда, расчётов с работниками и подотчётными лицами, налогов и взносов с зарплаты — проводки по ним наружу не отдаются.</summary>
        public string[] SensitiveAccountPrefixes { get; set; }
        /// <summary>Виды субконто «физлица / сотрудники» — проводки с ними в аналитике наружу не отдаются.</summary>
        public string[] SensitiveExtDimensionTypes { get; set; }
        public bool Tested { get; set; }

        // ----- Вкладка «Доступ» -----
        /// <summary>Все объекты, которые показывает дерево «Доступа» (включённые по умолчанию — ODataObjects).</summary>
        public string[] CatalogObjects { get; set; }
        /// <summary>Персональные данные — раздел «Зарплата и кадры» с замком: галочки недоступны.</summary>
        public string[] PersonalData { get; set; }
        /// <summary>Подсистемы зарплаты и кадров — объекты только из них уходят в закрытый раздел.</summary>
        public string[] LockedSubsystems { get; set; }
        /// <summary>Служебные подсистемы (администрирование, отчёты) — разделом объекта становятся, только если других нет.</summary>
        public string[] ServiceSubsystems { get; set; }
        /// <summary>Порядок разделов — как в левом меню 1С; подсистемы не из списка — следом по алфавиту.</summary>
        public string[] SectionOrder { get; set; }
        /// <summary>Объект в нескольких подсистемах — основной раздел по профилю.</summary>
        public Dictionary<string, string> SectionOverrides { get; set; }
        /// <summary>Запасная раскладка (если в конфигурации нет подсистем или разделы ещё не загружены): объект → раздел.</summary>
        public Dictionary<string, string> FallbackSections { get; set; }
        /// <summary>Человеческие имена по умолчанию (синонимы БП КЗ) — пока разделы не загружены из самой базы.</summary>
        public Dictionary<string, string> FallbackTitles { get; set; }

        public bool IsMoneyAccount(string code) =>
            !string.IsNullOrEmpty(code) && code.Length >= 4 && code.StartsWith(MoneyGroupCode.Substring(0, 2), StringComparison.Ordinal)
            && code != MoneyGroupCode && char.IsDigit(code[2]) && char.IsDigit(code[3]);
    }

