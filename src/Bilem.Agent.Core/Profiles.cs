        });

        public static readonly IReadOnlyList<ConfigProfile> All = new[] { BpKz };

        /// <summary>Профиль по имени конфигурации; для неизвестной — профиль БП КЗ как «лучшее предположение» (Tested=false).</summary>
        public static ConfigProfile For(string configurationName)
        {
            var p = All.FirstOrDefault(x => string.Equals(x.Configuration, configurationName, StringComparison.Ordinal));
            if (p != null) return p;
            return WithAccess(new ConfigProfile
            {
                Configuration = configurationName,
                ChartOfAccounts = BpKz.ChartOfAccounts,
                AccountingRegister = BpKz.AccountingRegister,
                Roles = BpKz.Roles,
                ODataObjects = DefaultODataObjects,
                MoneyGroupCode = BpKz.MoneyGroupCode,
                ClassifyMoney = BpKz.ClassifyMoney,
                SensitiveAccountPrefixes = BpKz.SensitiveAccountPrefixes,
                SensitiveExtDimensionTypes = BpKz.SensitiveExtDimensionTypes,
                Tested = false,
            });
        }
    }

