        /// <summary>«Бухгалтерия для Казахстана» 3.0: роли подобраны по ПравоДоступа на состав OData (заход 3).</summary>
        public static readonly ConfigProfile BpKz = WithAccess(new ConfigProfile
        {
            Configuration = "БухгалтерияДляКазахстана",
            ChartOfAccounts = "Типовой",
            AccountingRegister = "Типовой",
            Roles = new[]
            {
                "БазовыеПраваБСП", "БазовыеПраваБК", "ЧтениеДанныхБухгалтерии",
                "ЧтениеКурсовВалют", "ЧтениеЧековККМ", "ЧтениеОтчетаОРозничныхПродажах",
            },
            ODataObjects = DefaultODataObjects,
            MoneyGroupCode = "1000",
            // Касса — 1010; банк — 1030, 1040, 1050; прочие — остальные 10xx (в пути, ограниченные, электронные, резерв…)
            ClassifyMoney = code =>
                code.StartsWith("1010", StringComparison.Ordinal) ? CashClass.Cash
                : (code.StartsWith("1030", StringComparison.Ordinal) || code.StartsWith("1040", StringComparison.Ordinal) || code.StartsWith("1050", StringComparison.Ordinal)) ? CashClass.Bank
                : CashClass.Other,
            SensitiveAccountPrefixes = new[]
            {
                "1152", "125", "215", "3120", "3150", "321", "3220", "3350", "3384", "3386", "3430", "4164", "4166", "4230",
